# ---------------------------------------------------------------- 集計関数
def pct(x):
    return f"{x:.0f}%"


def dist(sub, key):
    col, opts = Q[key]
    s = sub[col].dropna()
    n = len(s)
    counts = [int((s == v).sum()) for v, _ in opts]
    assert sum(counts) == n, (key, s.value_counts())
    return n, counts, [c / n * 100 if n else float("nan") for c in counts]


def multi(sub, key):
    col, mp = MULTI[key]
    s = sub[col].dropna()
    n = len(s)
    items = s.str.split(",").explode().str.strip()
    assert items.isin(mp.keys()).all(), items[~items.isin(mp.keys())].unique()
    vc = items.value_counts()
    return n, {lab: (int(vc.get(k, 0)), vc.get(k, 0) / n * 100) for k, lab in mp.items()}


def score(sub, col):
    return sub[col].map(SCORE).dropna()


